static uint8_t gmul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        uint8_t hi = a & 0x80;
        a <<= 1;
        if (hi) a ^= 0x1b;
        b >>= 1;
    }
    return p;
}

static void inv_sub_bytes(uint8_t s[16]) {
    for (int i = 0; i < 16; i++) s[i] = INV_SBOX[s[i]];
}
static void inv_shift_rows(uint8_t s[16]) {
    uint8_t t;
    /* row 1: 1 byte right */
    t = s[13]; s[13]=s[9]; s[9]=s[5]; s[5]=s[1]; s[1]=t;
    /* row 2: 2 bytes right */
    t = s[2]; s[2]=s[10]; s[10]=t;
    t = s[6]; s[6]=s[14]; s[14]=t;
    /* row 3: 3 bytes right */
    t = s[3]; s[3]=s[7]; s[7]=s[11]; s[11]=s[15]; s[15]=t;
}
static void inv_mix_columns(uint8_t s[16]) {
    for (int c = 0; c < 4; c++) {
        uint8_t *col = s + c * 4;
        uint8_t a0 = col[0], a1 = col[1], a2 = col[2], a3 = col[3];
        col[0] = gmul(a0,0x0e) ^ gmul(a1,0x0b) ^ gmul(a2,0x0d) ^ gmul(a3,0x09);
        col[1] = gmul(a0,0x09) ^ gmul(a1,0x0e) ^ gmul(a2,0x0b) ^ gmul(a3,0x0d);
        col[2] = gmul(a0,0x0d) ^ gmul(a1,0x09) ^ gmul(a2,0x0e) ^ gmul(a3,0x0b);
        col[3] = gmul(a0,0x0b) ^ gmul(a1,0x0d) ^ gmul(a2,0x09) ^ gmul(a3,0x0e);
    }
}

static void aes_decrypt_block(const uint8_t *rk, int rounds, uint8_t s[16]) {
    add_round_key(s, rk + rounds * 16);
    for (int r = rounds - 1; r > 0; r--) {
        inv_shift_rows(s);
        inv_sub_bytes(s);
        add_round_key(s, rk + r * 16);
        inv_mix_columns(s);
    }
    inv_shift_rows(s);
    inv_sub_bytes(s);
    add_round_key(s, rk);
}

static void aes128_decrypt_block(const uint8_t key[16], const uint8_t in[16], uint8_t out[16]) {
    uint8_t rk[176];
    expand_key_128(key, rk);
    memcpy(out, in, 16);
    aes_decrypt_block(rk, 10, out);
}
static void aes256_decrypt_block(const uint8_t key[32], const uint8_t in[16], uint8_t out[16]) {
    uint8_t rk[240];
    expand_key_256(key, rk);
    memcpy(out, in, 16);
    aes_decrypt_block(rk, 14, out);
}

/* AES-CBC (NIST SP 800-38A §6.2) — no padding, len must be % 16. */

int ct_aes128_cbc_encrypt(const uint8_t key[16], const uint8_t iv[16],
                          const uint8_t *in, uint8_t *out, size_t len) {
    if (!key || !iv || !in || !out || (len % 16)) return CT_ERR_ARGS;
    uint8_t prev[16];
    memcpy(prev, iv, 16);
    for (size_t i = 0; i < len; i += 16) {
        uint8_t blk[16];
        for (int j = 0; j < 16; j++) blk[j] = in[i+j] ^ prev[j];
        ct_aes128_ecb_encrypt_block(key, blk, out + i);
        memcpy(prev, out + i, 16);
    }
    return CT_OK;
}

int ct_aes128_cbc_decrypt(const uint8_t key[16], const uint8_t iv[16],
                          const uint8_t *in, uint8_t *out, size_t len) {
    if (!key || !iv || !in || !out || (len % 16)) return CT_ERR_ARGS;
    uint8_t prev[16];
    memcpy(prev, iv, 16);
    for (size_t i = 0; i < len; i += 16) {
        uint8_t dec[16];
        aes128_decrypt_block(key, in + i, dec);
        for (int j = 0; j < 16; j++) out[i+j] = dec[j] ^ prev[j];
        memcpy(prev, in + i, 16);
    }
    return CT_OK;
}

