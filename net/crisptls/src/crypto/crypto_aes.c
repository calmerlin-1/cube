static const uint8_t RCON[11] = {0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36};

static uint8_t xtime(uint8_t x) { return (x << 1) ^ (0x1b & (0 - (x >> 7))); }

static void expand_key_128(const uint8_t key[16], uint8_t rk[176]) {
    memcpy(rk, key, 16);
    for (int i = 4; i < 44; i++) {
        uint8_t t[4];
        memcpy(t, rk + (i - 1) * 4, 4);
        if (i % 4 == 0) {
            uint8_t tmp = t[0];
            t[0] = SBOX[t[1]] ^ RCON[i / 4];
            t[1] = SBOX[t[2]];
            t[2] = SBOX[t[3]];
            t[3] = SBOX[tmp];
        }
        for (int j = 0; j < 4; j++) rk[i * 4 + j] = rk[(i - 4) * 4 + j] ^ t[j];
    }
}

static void expand_key_256(const uint8_t key[32], uint8_t rk[240]) {
    memcpy(rk, key, 32);
    for (int i = 8; i < 60; i++) {
        uint8_t t[4];
        memcpy(t, rk + (i - 1) * 4, 4);
        if (i % 8 == 0) {
            uint8_t tmp = t[0];
            t[0] = SBOX[t[1]] ^ RCON[i / 8];
            t[1] = SBOX[t[2]];
            t[2] = SBOX[t[3]];
            t[3] = SBOX[tmp];
        } else if (i % 8 == 4) {
            for (int j = 0; j < 4; j++) t[j] = SBOX[t[j]];
        }
        for (int j = 0; j < 4; j++) rk[i * 4 + j] = rk[(i - 8) * 4 + j] ^ t[j];
    }
}

static void add_round_key(uint8_t s[16], const uint8_t *rk) {
    for (int i = 0; i < 16; i++) s[i] ^= rk[i];
}

static void sub_bytes(uint8_t s[16]) {
    for (int i = 0; i < 16; i++) s[i] = SBOX[s[i]];
}

static void shift_rows(uint8_t s[16]) {
    uint8_t t;
    /* row 1: 1 byte left */
    t = s[1]; s[1]=s[5]; s[5]=s[9]; s[9]=s[13]; s[13]=t;
    /* row 2: 2 bytes left */
    t = s[2]; s[2]=s[10]; s[10]=t;
    t = s[6]; s[6]=s[14]; s[14]=t;
    /* row 3: 3 bytes left */
    t = s[3]; s[3]=s[15]; s[15]=s[11]; s[11]=s[7]; s[7]=t;
}

static void mix_columns(uint8_t s[16]) {
    for (int c = 0; c < 4; c++) {
        uint8_t *col = s + c * 4;
        uint8_t a0 = col[0], a1 = col[1], a2 = col[2], a3 = col[3];
        col[0] = xtime(a0) ^ (xtime(a1) ^ a1) ^ a2 ^ a3;
        col[1] = a0 ^ xtime(a1) ^ (xtime(a2) ^ a2) ^ a3;
        col[2] = a0 ^ a1 ^ xtime(a2) ^ (xtime(a3) ^ a3);
        col[3] = (xtime(a0) ^ a0) ^ a1 ^ a2 ^ xtime(a3);
    }
}

static void aes_block(const uint8_t *rk, int rounds, uint8_t s[16]) {
    add_round_key(s, rk);
    for (int r = 1; r < rounds; r++) {
        sub_bytes(s);
        shift_rows(s);
        mix_columns(s);
        add_round_key(s, rk + r * 16);
    }
    sub_bytes(s);
    shift_rows(s);
    add_round_key(s, rk + rounds * 16);
}

int ct_aes128_ecb_encrypt_block(const uint8_t key[16],
                                const uint8_t in[16], uint8_t out[16]) {
    uint8_t rk[176];
    expand_key_128(key, rk);
    memcpy(out, in, 16);
    aes_block(rk, 10, out);
    return CT_OK;
}

int ct_aes256_ecb_encrypt_block(const uint8_t key[32],
                                const uint8_t in[16], uint8_t out[16]) {
    uint8_t rk[240];
    expand_key_256(key, rk);
    memcpy(out, in, 16);
    aes_block(rk, 14, out);
    return CT_OK;
}

